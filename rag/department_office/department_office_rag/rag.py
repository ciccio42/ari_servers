"""DepartmentOfficeRag: the retrieval of the department resolutions, the class Assistente of rag_unisa
(rag_pipeline/rispondi.py) behind the interface of the RAG servers (ari_servers/rag.py).

For every question: the registers (attendance, meetings, mentions over all the minutes, when the planner calls a
tool), filters from the question (year, date, type of document), hybrid search on Qdrant (dense + sparse BGE-M3,
generated questions), reranking, newest editions, presence tables put back together, nearby items. The answer is
generated by the LLM server with the system prompt and the request returned here.
"""
import logging
from datetime import date
from pathlib import Path

from ari_servers.config import workspace_path
from ari_servers.rag import Chunk, Generator, Rag, Retrieval

from .config import DepartmentOfficeConfig
from .utils.registers import load_registers, needs_registers, plan_and_run
from .utils.rispondi import (_CITAZIONE_REGISTRO, ISTRUZIONI, REGOLA_FRASE_COMPLETA, ConfigRisposta, Filtri,
                             Fonte, _espandi, _ricomponi_presenze, _unisci, chiede_un_periodo, costruisci_contesto,
                             estrai_filtri, modelli_disponibili, recupera, verifica_modello, versioni_superate)

log = logging.getLogger("rag_department_office")

NOTHING_FOUND = "Nei documenti non trovo nulla che riguardi questa domanda."
_AUTO = object()  # cerca() asks the registers when the caller did not


class DepartmentOfficeRag(Rag):
    name = "department_office"

    def __init__(self, cfg: DepartmentOfficeConfig):
        super().__init__(cfg)
        kb = workspace_path(cfg.kb_dir)
        # ConfigRisposta of rag_unisa: read by its functions (planner of the registers: model, base_url, timeout,
        # num_ctx)
        self.answer_cfg = ConfigRisposta(
            db=kb / "qdrant", model=cfg.generator_model, base_url=cfg.ollama_url, emb_model=cfg.embedding_model,
            device=cfg.device, k=cfg.top_k, modo=cfg.mode, espansione=cfg.expansion,
            contesto_max=cfg.context_max_chars, num_ctx=cfg.num_ctx, max_tokens=cfg.max_new_tokens,
            temperature=cfg.temperature, timeout=cfg.timeout, registers_path=kb / "registers.json",
            use_registers=cfg.use_registers, ultime_versioni=cfg.latest_versions, riordino=cfg.reranker_model,
            candidati=cfg.candidates, risposte_complete=cfg.complete_sentences)
        self.client = self.models = self.emb = self.registers = self.riordinatore = None
        self.superate = {}

    # --- Rag

    def load(self) -> None:
        from qdrant_client import QdrantClient, models

        from .utils.embeddings import BGEM3

        cfg = self.answer_cfg
        if not Path(cfg.db).is_dir():
            raise SystemExit(f"index not found: {cfg.db} (kb_dir of rag_department_office)")
        self.models = models
        self.client = QdrantClient(path=str(cfg.db))
        self.emb = BGEM3(cfg.emb_model, device=cfg.device)
        self.registers = load_registers(Path(cfg.registers_path)) if cfg.use_registers else None
        self.superate = versioni_superate(self.client, models) if cfg.ultime_versioni else {}
        if cfg.riordino:
            from .utils.rerank import Riordinatore

            self.riordinatore = Riordinatore(cfg.riordino, device=cfg.device)
        # the model is used by the LLM server (and here by the planner of the registers): only a warning
        warning = verifica_modello(cfg)
        if warning:
            log.warning("generation model: %s", warning)

    def retrieve(self, question: str, history=None) -> Retrieval:
        # one question at a time, as rag_unisa: the history of the conversation is used by the generation only
        register = self.query_registers(question)
        fonti, filtri = self.cerca(question, register)
        info = {"filters": filtri.descrizione(), "registers": register.domanda_corrisposta if register else "",
                "sources": [{"source": f.etichetta(), "via": f.via, "matched_question": f.domanda_corrisposta}
                            for f in fonti]}
        chunks = [Chunk(text=f.testo, source=self._source(f), score=round(float(f.punteggio), 4)) for f in fonti]
        if not fonti:
            return Retrieval(chunks=[], answer=NOTHING_FOUND, info=info)
        system = ISTRUZIONI.replace("{frase_completa}", REGOLA_FRASE_COMPLETA if self.cfg.complete_sentences else "")
        system = system.replace("{oggi}", date.today().strftime("%d/%m/%Y"))
        context = costruisci_contesto(fonti, self.cfg.context_max_chars)
        return Retrieval(chunks=chunks, system=system, user=f"DOCUMENTI RECUPERATI\n\n{context}\n\nDOMANDA: {question}",
                         drop_patterns=[_CITAZIONE_REGISTRO.pattern], info=info)

    def generator(self) -> Generator:
        # think off, the same num_ctx of the planner: a different value makes Ollama load the model again
        return Generator(self.cfg.generator_backend, self.cfg.generator_model, self.cfg.temperature,
                         self.cfg.max_new_tokens, {"num_ctx": self.cfg.num_ctx, "think": False})

    def describe(self) -> dict:
        available = modelli_disponibili(self.cfg.ollama_url, timeout=2.0)
        return {**super().describe(), "embedding_model": self.cfg.embedding_model,
                "reranker_model": self.cfg.reranker_model, "registers": self.registers is not None,
                "generator_available": None if available is None else self.cfg.generator_model in available}

    # --- Assistente of rag_unisa

    @staticmethod
    def _source(f: Fonte) -> str:
        return f.etichetta() + (f" > {' > '.join(f.percorso)}" if f.percorso else "")

    def _ultime_versioni(self, fonti: list, vettori) -> list:
        """Replaces chunks of superseded editions with chunks of the newest edition (Assistente._ultime_versioni)."""
        tolti: dict = {}
        for f in fonti:
            nuova = self.superate.get(f.file)
            if nuova is not None:
                tolti[nuova] = tolti.get(nuova, 0) + 1
        if not tolti:
            return fonti

        candidati: dict = {}
        for nuova, quanti in tolti.items():
            condizione = self.models.Filter(must=[self.models.FieldCondition(
                key="source_path", match=self.models.MatchValue(value=nuova))])
            candidati[nuova] = recupera(self.client, self.models, vettori, quanti + len(fonti),
                                        self.answer_cfg.modo, Filtri(), condizione=condizione)

        risultato, messi = [], set()
        for f in fonti:
            nuova = self.superate.get(f.file)
            if nuova is None:
                scelta = f
            else:
                coda = candidati[nuova]
                while coda and coda[0].chunk_id in messi:
                    coda.pop(0)
                if not coda:
                    continue
                scelta = coda.pop(0)
            if scelta.chunk_id not in messi:
                risultato.append(scelta)
                messi.add(scelta.chunk_id)
        return risultato

    def cerca(self, domanda: str, register_source=_AUTO):
        """Retrieved sources and filters of the question (Assistente.cerca)."""
        cfg = self.answer_cfg
        if register_source is _AUTO:
            register_source = self.query_registers(domanda)
        filtri = estrai_filtri(domanda)
        vettori = self.emb.encode([domanda], mostra_avanzamento=False)
        k = cfg.k if register_source is None else max(2, cfg.k // 4)

        n = max(k, cfg.candidati) if self.riordinatore else k
        libere = recupera(self.client, self.models, vettori, n, cfg.modo, Filtri())
        if filtri.year or filtri.doc_type:
            mirate = recupera(self.client, self.models, vettori, n, cfg.modo, filtri)
            fonti = _unisci(mirate, libere, n)
        else:
            fonti = libere
        if self.superate and not chiede_un_periodo(domanda, filtri):
            fonti = self._ultime_versioni(fonti, vettori)
        if self.riordinatore and len(fonti) > k:
            punteggi = self.riordinatore.punteggi(domanda, [f.testo for f in fonti])
            ordine = sorted(range(len(fonti)), key=lambda i: -punteggi[i])
            fonti = [fonti[i] for i in ordine[:k]]
        if register_source is None:
            fonti = _ricomponi_presenze(self.client, self.models, fonti)
        fonti = _espandi(self.client, self.models, fonti, cfg.espansione if register_source is None else 0)
        if register_source is not None:
            # the register covers every meeting: presence fragments of a single meeting would only take space
            fonti = [register_source] + [f for f in fonti if f.genere != "table_presence"]
        return fonti, filtri

    def query_registers(self, domanda: str):
        """Register answer for questions over many meetings, as a context source (Assistente.query_registers)."""
        cfg = self.answer_cfg
        if self.registers is None or not cfg.use_registers or not needs_registers(domanda):
            return None
        answer = plan_and_run(cfg, self.registers, domanda)
        if answer is None:
            return None
        return Fonte(chunk_id=f"registro:{answer.key}", documento=answer.title, data="", percorso=[],
                     testo=answer.text, punteggio=1.0, via="registro", domanda_corrisposta="; ".join(answer.calls),
                     genere="register")
